#!/usr/bin/env python3
"""Generate a repeatable bumpy lake mesh and nearby sonar test targets."""

import argparse
from copy import deepcopy
import math
from pathlib import Path
import xml.etree.ElementTree as ET

import numpy as np


MOUNDS = ((-15, -9, 0.8, 1.7, 1.2), (-8, -6, 0.9, 2.0, 1.4),
          (-11, -13, 0.6, 1.5, 0.9))
TRENCH = (-13, -5, -0.9, 4.0, 0.6)
ROCKS = ((-9.0, -7.8, 0.7, 0.6, 0.65),
         (-14.0, -10.0, 0.95, 0.7, 0.8),
         (-8.0, -5.5, 0.65, 0.8, 0.6))


def read_obj(path):
    """Read mesh vertices and triangulate faces without relying on OBJ normals."""
    vertices, faces = [], []
    for line in Path(path).read_text().splitlines():
        fields = line.split('#', 1)[0].split()
        if not fields:
            continue
        if fields[0] == 'v':
            vertices.append([float(value) for value in fields[1:4]])
        elif fields[0] == 'f':
            indices = [int(value.split('/')[0]) for value in fields[1:]]
            if any(index == 0 or abs(index) > len(vertices) for index in indices):
                raise ValueError('Invalid OBJ face index')
            indices = [index - 1 if index > 0 else len(vertices) + index for index in indices]
            faces.extend((indices[0], indices[i], indices[i + 1])
                         for i in range(1, len(indices) - 1))
    return np.asarray(vertices, dtype=float), np.asarray(faces, dtype=int)


def deform_terrain(vertices, seed=42, roughness=0.35, feature_scale=1.0):
    """Add smooth roughness, three mounds and a trench below the shoreline."""
    if not np.isfinite(roughness) or roughness < 0:
        raise ValueError('roughness must be finite and nonnegative')
    if not np.isfinite(feature_scale) or feature_scale < 0:
        raise ValueError('feature_scale must be finite and nonnegative')
    result = vertices.copy()
    x, y, z = vertices.T
    random = np.random.default_rng(seed)
    angles = random.uniform(0, 2 * math.pi, 16)
    wave_numbers = 2 * math.pi / random.uniform(2.5, 8.0, 16)
    phases = random.uniform(0, 2 * math.pi, 16)
    noise = np.sin(x[:, None] * (np.cos(angles) * wave_numbers)
                   + y[:, None] * (np.sin(angles) * wave_numbers) + phases).mean(axis=1)
    features = np.zeros(len(vertices))
    for cx, cy, height, sx, sy in (*MOUNDS, TRENCH):
        features += height * np.exp(-0.5 * (((x - cx) / sx)**2 + ((y - cy) / sy)**2))
    # Preserve water geometry, the shoreline and every above-water vertex.
    underwater = np.clip((-z - 0.8) / 2.0, 0, 1)
    result[:, 2] += underwater * (2 * roughness * noise + feature_scale * features)
    return result


def write_obj(path, vertices, faces):
    """Recompute area-weighted normals after deformation and write an OBJ mesh."""
    triangles = vertices[faces]
    face_normals = np.cross(triangles[:, 1] - triangles[:, 0],
                            triangles[:, 2] - triangles[:, 0])
    normals = np.zeros_like(vertices)
    for corner in range(3):
        np.add.at(normals, faces[:, corner], face_normals)
    lengths = np.linalg.norm(normals, axis=1)
    normals[lengths > 0] /= lengths[lengths > 0, None]
    normals[lengths == 0] = (0, 0, 1)
    with Path(path).open('w', newline='\n') as stream:
        stream.write('# Generated by ros2_ws/scripts/generate_lake_terrain.py\n')
        for vertex in vertices:
            stream.write('v {:.9f} {:.9f} {:.9f}\n'.format(*vertex))
        for normal in normals:
            stream.write('vn {:.9f} {:.9f} {:.9f}\n'.format(*normal))
        for face in faces + 1:
            stream.write('f ' + ' '.join(f'{index}//{index}' for index in face) + '\n')


def terrain_height(vertices, faces, x, y):
    """Interpolate on the actual triangle surface to ground objects accurately."""
    triangles = vertices[faces]
    xy = triangles[:, :, :2]
    candidates = np.flatnonzero(
        np.all(xy.min(axis=1) <= (x, y), axis=1)
        & np.all(xy.max(axis=1) >= (x, y), axis=1))
    for index in candidates:
        triangle = triangles[index]
        matrix = np.column_stack((triangle[1, :2] - triangle[0, :2],
                                  triangle[2, :2] - triangle[0, :2]))
        if abs(np.linalg.det(matrix)) < 1e-12:
            continue
        u, v = np.linalg.solve(matrix, np.array((x, y)) - triangle[0, :2])
        if u >= -1e-9 and v >= -1e-9 and u + v <= 1 + 1e-9:
            return float((1 - u - v) * triangle[0, 2] + u * triangle[1, 2]
                         + v * triangle[2, 2])
    raise ValueError(f'Point ({x}, {y}) is outside the terrain')


def rock_mesh(radii, seed):
    """Build a small irregular closed boulder mesh with outward face winding."""
    random = np.random.default_rng(seed)
    phase = random.uniform(0, 2 * math.pi)
    vertices = [(0, 0, 1)]
    rings, sectors = 8, 16
    for ring in range(1, rings):
        theta = math.pi * ring / rings
        for sector in range(sectors):
            phi = 2 * math.pi * sector / sectors
            radius = 1 + 0.1 * math.sin(3 * phi + phase) * math.sin(theta)**2
            vertices.append((radius * math.sin(theta) * math.cos(phi),
                             radius * math.sin(theta) * math.sin(phi),
                             radius * math.cos(theta)))
    vertices.append((0, 0, -1))
    faces = []
    for sector in range(sectors):
        a, b = 1 + sector, 1 + (sector + 1) % sectors
        faces.append((0, a, b))
        for ring in range(rings - 2):
            c, d = a + sectors, b + sectors
            faces.extend(((a, c, b), (b, c, d)))
            a, b = c, d
        faces.append((a, len(vertices) - 1, b))
    return np.asarray(vertices) * radii, np.asarray(faces)


def add_target(model, name, pose, geometry):
    """Use identical visual and collision geometry for each stationary target."""
    link = ET.SubElement(model, 'link', name=name)
    ET.SubElement(link, 'pose').text = ' '.join(f'{value:.9f}' for value in pose)
    for tag in ('collision', 'visual'):
        item = ET.SubElement(link, tag, name=name)
        item.append(deepcopy(geometry))
        if tag == 'visual':
            material = ET.SubElement(item, 'material')
            ET.SubElement(material, 'ambient').text = '0.35 0.38 0.42 1'
            ET.SubElement(material, 'diffuse').text = '0.35 0.38 0.42 1'


def generate(package, seed=42, roughness=0.35, feature_scale=1.0):
    """Keep terrain.obj as the baseline, so repeated runs never compound bumps."""
    models = Path(package) / 'models'
    baseline = models / 'lake_terrain/meshes/terrain.obj'
    vertices, faces = read_obj(baseline)
    vertices = deform_terrain(vertices, seed, roughness, feature_scale)
    write_obj(baseline.with_name('terrain_bumpy.obj'), vertices, faces)
    target_folder = models / 'sonar_targets'
    meshes = target_folder / 'meshes'
    meshes.mkdir(parents=True, exist_ok=True)
    sdf = ET.Element('sdf', version='1.10')
    model = ET.SubElement(sdf, 'model', name='sonar_targets')
    ET.SubElement(model, 'static').text = 'true'
    for index, (x, y, rx, ry, rz) in enumerate(ROCKS, 1):
        rock_vertices, rock_faces = rock_mesh((rx, ry, rz), seed + index)
        write_obj(meshes / f'boulder_{index}.obj', rock_vertices, rock_faces)
        floor = terrain_height(vertices, faces, x, y)
        geometry = ET.fromstring('<geometry><mesh><uri>'
                                 f'model://sonar_targets/meshes/boulder_{index}.obj'
                                 '</uri></mesh></geometry>')
        add_target(model, f'boulder_{index}', (x, y, floor + rz * 0.65, 0, 0, 0), geometry)
    # The wall crosses the forward beam near the initial robot position.
    x, y, height = -6.8, -8.0, 4.5
    floor = min(terrain_height(vertices, faces, x + dx, y + dy)
                for dx in (-0.2, 0.2) for dy in (-3.0, 0, 3.0))
    geometry = ET.fromstring('<geometry><box><size>0.4 6 4.5</size></box></geometry>')
    add_target(model, 'wall', (x, y, floor - 0.2 + height / 2, 0, 0, 0), geometry)
    ET.indent(sdf, space='  ')
    ET.ElementTree(sdf).write(target_folder / 'model.sdf', encoding='utf-8',
                              xml_declaration=True)
    (target_folder / 'model.config').write_text(
        '<?xml version="1.0"?>\n<model><name>Sonar test targets</name><version>1.0</version>'
        '<sdf version="1.10">model.sdf</sdf><description>Three boulders and a wall near '
        'the lake test-area spawn.</description></model>\n')
    spawn_z = terrain_height(vertices, faces, -12, -8) + 2.5
    print(f'Generated bumpy terrain, three boulders and a wall (seed={seed}).')
    print(f'Recommended robot spawn: -12 -8 {spawn_z:.6f} 0 0 0')
    return vertices, faces


def main():
    """Expose deterministic roughness controls without modifying the lake world."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--package', type=Path,
                        default=Path(__file__).resolve().parents[1] / 'src/pobs_gazebo')
    parser.add_argument('--seed', type=int, default=42)
    parser.add_argument('--roughness', type=float, default=0.35, help='smooth noise amplitude, m')
    parser.add_argument('--feature-scale', type=float, default=1.0,
                        help='mound/trench height scale')
    args = parser.parse_args()
    generate(args.package, args.seed, args.roughness, args.feature_scale)


if __name__ == '__main__':
    main()
